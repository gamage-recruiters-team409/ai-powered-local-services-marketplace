export function CategoryTradeIcon({ iconKey, size = 20 }) {
  switch (iconKey) {
    case 'sun':
      return <SunIcon size={size} />
    case 'snowflake':
      return <SnowflakeIcon size={size} />
    case 'sparkles':
      return <SparklesIcon size={size} />
    case 'hammer':
      return <HammerIcon size={size} />
    case 'award':
      return <AwardIcon size={size} />
    case 'shield':
      return <ShieldCheckIcon size={size} />
    default:
      return <WrenchIcon size={size} />
  }
}
